import assert from 'node:assert/strict';
import { test } from 'node:test';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { migrate } from '../apps/api/src/migrations.js';
import { createRepository } from '../apps/api/src/repository.js';
import { createApp } from '../apps/api/src/app.js';

test('pattern details: browsing, corrections, conflicts, removal and imports', { timeout: 60000 }, async t => {
  const connectionString = process.env.TEST_DATABASE_URL || process.env.DATABASE_URL;
  assert.ok(connectionString, 'Configure DATABASE_URL or TEST_DATABASE_URL.');
  const admin = new pg.Pool({ connectionString, connectionTimeoutMillis: 5000 });
  const schema = `dsa_journal_${randomUUID().replaceAll('-', '')}`;
  let pool, server;
  await admin.query(`CREATE SCHEMA "${schema}"`);
  t.after(async () => {
    if (server) await new Promise(resolve => server.close(resolve));
    if (pool) await pool.end();
    try { await admin.query(`DROP SCHEMA "${schema}" CASCADE`); } finally { await admin.end(); }
  });
  pool = new pg.Pool({ connectionString, options: `-c search_path=${schema}`, connectionTimeoutMillis: 5000 });
  await migrate(pool);
  const repository=createRepository(pool);
  server = createApp({ repository }).listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function api(path, method = 'GET', body, status = 200) {
    const response = await fetch(base + path, { method, headers: body === undefined ? {} : { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    const result = await response.json();
    assert.equal(response.status, status, JSON.stringify(result));
    return result;
  }
  const input = { url: 'https://leetcode.com/problems/two-sum/', title: 'Two Sum', patternSlugs: ['two-pointers'] };
  const problem = (await api('/problems', 'POST', input, 201)).problem;
  const second = (await api('/problems', 'POST', { url: 'https://leetcode.com/problems/valid-parentheses/', title: 'Valid Parentheses' }, 201)).problem;
  assert.equal((await repository.summary()).attempts, 0);
  await api('/imports', 'POST', { problemIds: [second.id] });
  assert.equal((await repository.summary()).historical, 1);
  assert.equal((await api('/pattern-problems?status=historical')).total, 1);
  assert.equal((await api('/pattern-problems?status=unpracticed')).total, 2);
  assert.equal((await api('/pattern-problems?q=TWO')).problems[0].id, problem.id);
  assert.equal((await api('/pattern-problems?q=%25')).total, 0); // literal wildcard characters
  const attempt = { requestId: randomUUID(), problemId: problem.id, assistance: 'hint', patternSlugs: ['arrays-hashing'], notes: 'original', attemptedAt: '2025-01-01T12:00:00.000Z' };
  await api('/attempts', 'POST', attempt, 201);
  assert.equal((await api('/pattern-problems?pattern=arrays-hashing')).total, 1);
  assert.equal((await api('/pattern-problems?pattern=two-pointers')).total, 1);
  assert.equal((await api('/pattern-problems?status=practiced')).total, 1);
  const update = { revision: 1, assistance: 'independent', patternSlugs: ['binary-search'], notes: 'corrected', attemptedAt: '2025-01-02T12:00:00.000Z' };
  const corrected = (await api(`/attempts/${attempt.requestId}`, 'PUT', update)).attempt;
  assert.equal(corrected.revision, 2);
  assert.deepEqual(corrected.patternSlugs, ['binary-search']);
  assert.equal((await repository.summary()).independent, 1);
  assert.equal((await repository.summary()).patterns.find(p => p.slug === 'binary-search').practiced, 1);
  assert.equal((await api('/pattern-problems?pattern=arrays-hashing')).total, 0);
  await api(`/attempts/${attempt.requestId}`, 'PUT', update, 409);
  await api(`/attempts/${attempt.requestId}`, 'DELETE', { revision: 1 }, 409);
  await api(`/attempts/${attempt.requestId}`, 'PUT', { ...update, revision: 2, patternSlugs: ['missing'] }, 400);
  assert.equal((await api('/attempts')).attempts[0].revision, 2);
  const replay = await api('/attempts', 'POST', attempt);
  assert.equal(replay.attempt.notes, 'corrected');
  await api(`/problems/${problem.id}`, 'PUT', { ...input, title: 'Renamed', difficulty: 'easy', patternSlugs: ['sliding-window'] });
  assert.equal((await api('/attempts')).attempts[0].problem.title, 'Renamed');
  assert.deepEqual((await api('/attempts')).attempts[0].patternSlugs, ['binary-search']);
  await api(`/problems/${problem.id}`, 'PUT', { ...input, url: second.url }, 400);
  const older = { ...attempt, requestId: randomUUID(), assistance: 'solution', attemptedAt: '2024-12-01T12:00:00.000Z' };
  await api('/attempts', 'POST', older, 201);
  await api(`/attempts/${attempt.requestId}`, 'DELETE', { revision: 2 });
  await api(`/attempts/${attempt.requestId}`, 'DELETE', { revision: 2 });
  assert.equal((await repository.summary()).independent, 0);
  await api('/attempts', 'POST', attempt, 409);
  await api(`/attempts/${attempt.requestId}`, 'PUT', { ...update, revision: 3 }, 404);
  await api(`/attempts/${older.requestId}`, 'DELETE', { revision: 1 });
  assert.equal((await repository.summary()).attempts, 0);
  assert.equal((await api('/pattern-problems?status=practiced')).total, 0);
  await api(`/imports/${second.id}`, 'DELETE');
  assert.equal((await repository.summary()).historical, 0);
  assert.equal((await api('/pattern-problems?limit=1&offset=1')).problems.length, 1);
  assert.equal((await api('/pattern-problems?offset=100')).total, 2);
  const capture = { requestId: randomUUID(), url: 'https://leetcode.com/problems/capture-fixture/', title: 'Capture fixture', topics: ['Array','Hash Table'], selectedTopics: [], assistance: 'hint', attemptedAt: '2025-01-01T12:00:00.000Z' };
  const captured = (await api('/capture','POST',capture,201)).attempt;
  assert.equal(captured.patternSource,'inferred');
  assert.deepEqual(captured.patternSlugs,['arrays-hashing']);
  assert.equal((await api('/capture','POST',capture)).created,false);
  assert.equal((await repository.summary()).attempts,1);
  assert.equal((await repository.summary()).patterns.find(p=>p.slug==='arrays-hashing').practiced,0);
  assert.equal((await api('/pattern-problems?pattern=arrays-hashing')).total,1);
  await api('/capture','POST',{...capture,url:'https://leetcode.com/problems/conflicting-fixture/'},409);
  assert.equal((await api('/pattern-problems?q=conflicting-fixture')).total,0);
  const noteEdit={revision:captured.revision,assistance:captured.assistance,patternSlugs:captured.patternSlugs,notes:'note only',attemptedAt:captured.attemptedAt};
  assert.equal((await api('/attempts/'+captured.id,'PUT',noteEdit)).attempt.patternSource,'inferred');
  const explicit=(await api('/capture','POST',{...capture,requestId:randomUUID(),selectedTopics:['Array']},201)).attempt;
  assert.equal(explicit.patternSource,'explicit');
  assert.equal((await repository.summary()).patterns.find(p=>p.slug==='arrays-hashing').practiced,1);
  const noTopics=(await api('/capture','POST',{...capture,requestId:randomUUID(),url:'https://leetcode.com/problems/no-topics/',topics:[]},201)).attempt;
  assert.deepEqual(noTopics.patternSlugs,['uncategorized']);
  await api('/capture','POST',{...capture,requestId:randomUUID(),selectedTopics:['Trees']},400);
  await api('/attempts/'+captured.id,'DELETE',{revision:2});
  await api('/capture','POST',capture,409);
  await api('/pattern-problems?status=wrong', 'GET', undefined, 400);
  await api('/attempts/not-a-uuid', 'DELETE', { revision: 1 }, 400);
  await api(`/attempts/${randomUUID()}`, 'DELETE', { revision: 1 }, 404);
});
